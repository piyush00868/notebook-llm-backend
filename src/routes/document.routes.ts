import { Router } from "express";
import { createDocumentController, getDocumentController, deleteDocumentController, uploadPdfController, uploadUrlController, uploadYoutubeController, uploadTextController } from "../controllers/document.controller";
import { requireAuth } from "../middleware/auth.middleware";
import { uploadPdf } from "../middleware/upload.middleware";
import { youtubeLimiter, youtubeDailyLimiter, pdfLimiter, urlLimiter, textLimiter } from "../middleware/rateLimit.middleware";
const router = Router();
router.use(requireAuth);
router.post("/", createDocumentController);
router.get("/:id", getDocumentController);
router.post("/upload", uploadPdf.single("file"), pdfLimiter, uploadPdfController);
router.delete("/:id", deleteDocumentController);
router.post("/youtube", youtubeLimiter, youtubeDailyLimiter, uploadYoutubeController);
router.post("/url", urlLimiter, uploadUrlController);
router.post("/text", textLimiter, uploadTextController);
export default router;